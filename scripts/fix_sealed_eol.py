"""Make hash-sealed files byte-exact in git, independent of OS line-ending settings.

Background: the Amendment 05 sidecar and the test-open lock record SHA-256 hashes of
raw file bytes. They were sealed on a Windows working tree where some files had CRLF
and others LF. Git (core.autocrlf / text=auto) normalizes to LF in the repository, so
a fresh clone hashes differently and the lock verification fails although no content
changed.

This tool (idempotent, never touches content other than line endings):
  1. Collects every sealed path from the lock files.
  2. For each present file, keeps the bytes if they already match the sealed hash;
     otherwise tries the all-LF and all-CRLF variants of the same content.
  3. Writes the matching variant back and reports files that match none (those need a
     human decision: the content really differs, or the original had mixed endings).
  4. Regenerates the managed block of .gitattributes marking sealed files `-text`,
     so git stores and checks them out byte-for-byte on every platform.

Usage: python scripts/fix_sealed_eol.py [--check]   (--check changes nothing)
After running: git add --renormalize . && git status   (then commit)
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "# BEGIN sealed-files (generated by scripts/fix_sealed_eol.py)"
END = "# END sealed-files"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sealed_hashes() -> dict[str, str]:
    sidecar = json.loads((ROOT / "config" / "amendment_05_test_open.lock.json").read_text(encoding="utf-8"))
    sealed: dict[str, str] = {
        "config/amendment_05_test_open.yaml": sidecar["config_sha256"],
        "outputs/metrics/day3_pretest_freeze.json": sidecar["frozen_manifest_sha256"],
    }
    sealed.update(sidecar.get("frozen_sources_sha256", {}))
    opened = ROOT / "outputs" / "metrics" / "test_opened.lock.json"
    if opened.is_file():
        sealed.update(json.loads(opened.read_text(encoding="utf-8")).get("input_hashes", {}))
    amendment_06 = ROOT / "config" / "amendment_06_ho2.lock.json"
    if amendment_06.is_file():
        amendment = json.loads(amendment_06.read_text(encoding="utf-8"))
        sealed["config/amendment_06_ho2.yaml"] = amendment["config_sha256"]
        sealed["docs/analysis_plan_amendment06_ho2.md"] = amendment["protocol_sha256"]
        sealed.update(amendment.get("frozen_source_sha256", {}))
    return sealed


def variants(data: bytes) -> dict[str, bytes]:
    lf = data.replace(b"\r\n", b"\n")
    return {"LF": lf, "CRLF": lf.replace(b"\n", b"\r\n")}


def main() -> int:
    check_only = "--check" in sys.argv
    ok, fixed, mismatched, absent = [], [], [], []
    for rel, expected in sorted(sealed_hashes().items()):
        path = ROOT / rel
        if not path.is_file():
            absent.append(rel)
            continue
        data = path.read_bytes()
        if sha(data) == expected:
            ok.append(rel)
            continue
        match = next((name for name, blob in variants(data).items() if sha(blob) == expected), None)
        if match is None:
            mismatched.append(rel)
            continue
        if not check_only:
            path.write_bytes(variants(data)[match])
        fixed.append(f"{rel} -> {match}")

    tracked = sorted(set(ok) | {item.split(" -> ")[0] for item in fixed} | set(mismatched))
    if not check_only:
        gitattributes = ROOT / ".gitattributes"
        existing = gitattributes.read_text(encoding="utf-8") if gitattributes.exists() else ""
        if BEGIN in existing:
            existing = existing.split(BEGIN)[0].rstrip("\n") + ("\n" if existing.split(BEGIN)[0].strip() else "")
        block = "\n".join([BEGIN, "# Hash-sealed files: store and check out byte-for-byte (no EOL conversion)."] + [f"{p} -text" for p in tracked] + [END, ""])
        gitattributes.write_text(existing + block, encoding="utf-8", newline="\n")

    print(f"already byte-exact: {len(ok)}")
    print(f"{'would fix' if check_only else 'fixed'} line endings: {len(fixed)}")
    for line in fixed:
        print("   ", line)
    print(f"not shipped in this checkout (cannot verify here): {len(absent)}")
    print(f"MATCH NEITHER LF NOR CRLF (needs attention): {len(mismatched)}")
    for rel in mismatched:
        print("   ", rel)
    return 1 if mismatched else 0


if __name__ == "__main__":
    raise SystemExit(main())
